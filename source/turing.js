// Runs Entire's own uninstall, then cleans what's left: hook files Entire wrote (put back the .pre-entire original, if any)
// and install-wd's wd_commit_hook with its one-line calls. `enable` re-adds turing's lines afterwards.
function removeEntire(top) {
  console.log(`  ${top}`);
  if (onPath('entire')) {
    try {
      execFileSync('entire', ['disable', '--uninstall', '--force'], { cwd: top, stdio: ['ignore', 'ignore', 'inherit'] });
      console.log('    ✓ Entire uninstalled');
    } catch { console.log('    ⚠ entire disable --uninstall failed; removing its hooks only'); }
  } else console.log("    ⚠ the entire command isn't on PATH; removing its hooks only");
  for (const d of hookDirs(top)) {
    for (const f of hookFiles(d)) {
      if (path.basename(f) === 'wd_commit_hook') { fs.rmSync(f); continue; }
      if (f.endsWith('.pre-entire') || !/entire hooks git/.test(readOr(f, ''))) continue;
      if (fs.existsSync(`${f}.pre-entire`)) fs.renameSync(`${f}.pre-entire`, f);
      else if (HOOKS.includes(path.basename(f))) fs.writeFileSync(f, '#!/bin/sh\n');
      else fs.rmSync(f);
    }
    for (const f of hookFiles(d)) {
      const text = readOr(f, ''), out = text.replace(/^.*(wd_commit_hook|# Waydev: append attribution).*\n?/gm, '');
      if (out !== text) fs.writeFileSync(f, out);
    }
  }
}

const isShellHook = text => {
  const bang = text && text.startsWith('#!') ? text.split('\n')[0] : '';
  return !bang || /\b(sh|bash|zsh|dash|ksh|ash)\b/.test(bang);
};

function installHooks(top) {
  const repo = repoOf(top);
  const dir = hookTarget(top);
  fs.mkdirSync(dir, { recursive: true });
  const created = [], modified = [], skipped = [];
  for (const name of HOOKS) {
    const file = path.join(dir, name);
    const existing = readOr(file, null);
    // Our line is shell; inserting it into a Python/Node/... hook would break that hook (and remove one an older version put
    // there).
    if (!isShellHook(existing)) {
      if (existing.includes(MARK_BEGIN)) fs.writeFileSync(file, stripBlock(existing));
      skipped.push(name);
      continue;
    }
    let text = existing == null ? '#!/bin/sh\n' : stripBlock(existing);
    const nl = text.startsWith('#!') ? text.indexOf('\n') + 1 || text.length : 0;
    text = text.slice(0, nl) + (nl && !text.slice(0, nl).endsWith('\n') ? '\n' : '') + hookBlock(name) + '\n' + text.slice(nl);
    fs.writeFileSync(file, text);
    fs.chmodSync(file, 0o755);
    const rel = slash(path.relative(top, file));
    if (existing == null && !rel.startsWith('..') && !rel.startsWith('.git/')) created.push(rel);
    else if (existing != null && git(['ls-files', '--error-unmatch', rel], top) != null) modified.push(rel);
  }
  if (created.length) {
    addExclude(top, created);
    writeJSON(path.join(repo.state, 'created.json'), [...new Set([...readJSON(path.join(repo.state, 'created.json'), []), ...created])]);
  }
  return { dir, modified, skipped };
}

// A hooks folder outside this repo (a global or shared core.hooksPath) serves other repos too.
function sharedHooks(top, dir) {
  const inside = (p, root) => { const r = path.relative(real(root), real(p)); return !r.startsWith('..') && !path.isAbsolute(r); };
  const common = path.resolve(top, (git(['rev-parse', '--git-common-dir'], top) || '.git').trim());
  return !inside(dir, top) && !inside(dir, common);
}

function disable(top) {
  const repo = repoOf(top);
  const dir = hookTarget(top);
  // Turing's lines do nothing in repos that aren't enabled, so leave a shared folder alone for the repos still using it.
  if (sharedHooks(top, dir)) console.log(`    note: ${dir} is shared with other repos; turing's lines stay there (inactive here)`);
  else for (const name of HOOKS) {
    const file = path.join(dir, name);
    const text = readOr(file, null);
    if (text == null || !text.includes(MARK_BEGIN)) continue;
    const rest = stripBlock(text);
    if (/^(#![^\n]*)?\s*$/.test(rest)) fs.rmSync(file); else fs.writeFileSync(file, rest);
  }
  const created = readJSON(path.join(repo.state, 'created.json'), []);
  if (created.length) removeExclude(top, created);
  opencodeOtel(top, repo, false);
  // Every worktree's own data, not just this one's, so nothing stale is picked up if the repo is enabled again.
  const trees = (git(['worktree', 'list', '--porcelain'], top) || '').split('\n').filter(l => l.startsWith('worktree ')).map(l => l.slice(9));
  for (const t of trees) { const w = repoOf(t); if (w) fs.rmSync(w.work, { recursive: true, force: true }); }
  fs.rmSync(repo.state, { recursive: true, force: true });
  fs.rmSync(repo.work, { recursive: true, force: true });
  console.log(`  ✓ ${top}`);
}

